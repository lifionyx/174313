    'minimumTTC',nan,'completed',false,'p95ReplanMs',nan, ...
    'maxAbsPhysicalJerk',nan,'collisionPASS',false, ...
    'ttcPASS',false,'completionPASS',false,'latencyPASS',false, ...
    'jerkPASS',false,'Overall_PASS',false, ...
    'backend',m.backend,'codeFingerprint',m.codeFingerprint, ...
    'matlabRelease',m.matlabRelease,'thresholdVersion',m.thresholdVersion, ...
    'runTimestampUTC',char(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd HH:mm:ss Z')));
end

function fingerprint=codeFingerprint(root)
% Content hash of the VDB algorithm, scenario, sensors and benchmark rules.
paths={'build_vdb_closed_loop.m','src/+sih/makeScenario.m', ...
    'src/+sih/actorStates.m','src/+sih/vdbAutonomy.m', ...
    'src/+sih/vdbMetrics.m','src/+sih/SensorSuite.m', ...
    'src/+sih/observe.m','src/+sih/predictActors.m', ...
    'src/+sih/assessRisk.m','src/+sih/behavior.m', ...
    'src/+sih/planTrajectory.m','src/+sih/checkTrajectory.m', ...
    'src/+sih/control.m','src/+sih/config.m', ...
    'src/+sih/benchmarkCase.m','src/+sih/vdbGoalReached.m', ...
    'tests/benchmark/makeManifest.m', ...
    'tests/benchmark/scoreCase.m','tests/benchmark/runCase.m', ...
    'tests/benchmark/benchmarkTests.m'};
md=java.security.MessageDigest.getInstance('SHA-256');
for k=1:numel(paths)
    file=fullfile(root,strrep(paths{k},'/',filesep));
    assert(exist(file,'file')==2,'Missing fingerprinted source: %s',file);
    md.update(uint8(paths{k}));
    md.update(uint8(fileread(file)));
end
fingerprint=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2)',1,[]));
end
